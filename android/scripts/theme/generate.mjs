import { readFileSync, writeFileSync } from "node:fs";
import { registerHooks } from "node:module";
import { extname } from "node:path";

const utilities = new URL(".", import.meta.resolve("@material/material-color-utilities"));
registerHooks({
  resolve(specifier, context, nextResolve) {
    // The pinned package omits .js on some of its own relative imports.
    if (
      context.parentURL?.startsWith(utilities.href) &&
      specifier.startsWith(".") &&
      !extname(specifier)
    ) {
      return nextResolve(specifier + ".js", context);
    }
    return nextResolve(specifier, context);
  },
});

const {
  argbFromHex,
  Hct,
  hexFromArgb,
  SchemeTonalSpot,
} = await import("@material/material-color-utilities");

// Android design uses Tonal Spot, the 2021 specification and the Phone platform.
const seeds = {
  DEFAULT: "#FFA500",
  GOLDEN_HOUR: "#BB731B",
  CITRUS_SPARK: "#F4E33C",
  BERRY_BLUSH: "#C22E5A",
  COTTON_SKY: "#E4ABC8",
  BLUE_HORIZON: "#3758A1",
  DAYDREAM: "#9CB7F2",
  DEEP_LAGOON: "#017562",
};
const roles = [
  "primary", "onPrimary", "primaryContainer", "onPrimaryContainer", "inversePrimary",
  "secondary", "onSecondary", "secondaryContainer", "onSecondaryContainer",
  "tertiary", "onTertiary", "tertiaryContainer", "onTertiaryContainer",
  "surface", "onSurface", "surfaceVariant", "onSurfaceVariant", "surfaceDim",
  "surfaceBright", "surfaceContainerLowest", "surfaceContainerLow", "surfaceContainer",
  "surfaceContainerHigh", "surfaceContainerHighest", "outline", "outlineVariant",
  "inverseSurface", "inverseOnSurface", "scrim", "error", "onError", "errorContainer",
  "onErrorContainer", "primaryFixed", "primaryFixedDim", "onPrimaryFixed",
  "onPrimaryFixedVariant", "secondaryFixed", "secondaryFixedDim", "onSecondaryFixed",
  "onSecondaryFixedVariant", "tertiaryFixed", "tertiaryFixedDim", "onTertiaryFixed",
  "onTertiaryFixedVariant", "surfaceTint",
];
const output = new URL(
  "../../app/src/main/kotlin/ai/okou/android/PaletteColorSchemes.kt",
  import.meta.url,
);

function renderScheme(seed, dark) {
  const scheme = new SchemeTonalSpot(Hct.fromInt(argbFromHex(seed)), dark, 0, "2021", "phone");
  const darkOrLight = dark ? "dark" : "light";
  const bindings = { ...Object.fromEntries(roles.map((role) => [role, scheme[role]])),
    background: scheme.surface, onBackground: scheme.onSurface };
  const lines = Object.entries(bindings).map(([role, color]) => {
    if (!Number.isInteger(color)) throw new Error(`Missing Material role: ${role}`);
    const rgb = hexFromArgb(color).slice(1).toUpperCase();
    return `            ${role} = Color(0xFF${rgb}),`;
  });
  return [`        ${darkOrLight}ColorScheme(`, ...lines, "        )"].join("\n");
}

function schemeFunctionName(palette) {
  const [first, ...rest] = palette.toLowerCase().split("_");
  return first + rest.map((part) => part[0].toUpperCase() + part.slice(1)).join("") + "Colors";
}

const branches = Object.keys(seeds).map(
  (palette) => `        UserPreferencesColorTheme.${palette} -> ${schemeFunctionName(palette)}(dark)`,
);
const schemes = Object.entries(seeds).map(([palette, seed]) =>
  [
    `private fun ${schemeFunctionName(palette)}(dark: Boolean): ColorScheme =`,
    "    if (dark)",
    renderScheme(seed, true),
    "    else",
    renderScheme(seed, false),
  ].join("\n"),
);
const content = [
  "// Generated by android/scripts/theme/generate.mjs.",
  "package ai.okou.android",
  "",
  "import ai.okou.android.api.generated.UserPreferencesColorTheme",
  "import androidx.compose.material3.ColorScheme",
  "import androidx.compose.material3.darkColorScheme",
  "import androidx.compose.material3.lightColorScheme",
  "import androidx.compose.ui.graphics.Color",
  "",
  "internal fun resolvePalette(palette: UserPreferencesColorTheme, dark: Boolean): ColorScheme =",
  "    when (palette) {",
  ...branches,
  "    }",
  "",
  schemes.join("\n\n"),
  "",
].join("\n");

const args = process.argv.slice(2);
if (args.length === 0) {
  writeFileSync(output, content);
} else if (args.length === 1 && args[0] === "--check") {
  if (readFileSync(output, "utf8") !== content) {
    console.error("Android palette colors are out of date. Run node scripts/theme/generate.mjs.");
    process.exitCode = 1;
  }
} else {
  console.error("Usage: node scripts/theme/generate.mjs [--check]");
  process.exitCode = 2;
}
