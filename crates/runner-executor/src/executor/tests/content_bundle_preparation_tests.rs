use super::super::{NewSandboxDispatch, execute_job, execute_job_reuse};
use super::support::{
    default_params, make_reusable_idle_sandbox, minimal_context,
    test_executor_config_with_startup_api,
};
use runner_types::types::SandboxReuseResult;
use sandbox::SandboxId;
use sandbox_mock::{MockSandboxFactory, MockSandboxOverrides};
use std::sync::Arc;
use tokio_util::sync::CancellationToken;

#[tokio::test]
async fn cached_packages_install_on_fresh_and_reused_sandboxes() {
    let directory = tempfile::tempdir().unwrap();
    let (config, _startup_api) = test_executor_config_with_startup_api(directory.path()).await;
    let archive = include_bytes!("../../../tests/fixtures/content-bundle-v1.tar.gz");
    let hash = "d1467f9f02022e04ad66f2e983158c80ea58a152e8eec1ea7d07b0f51d3b3c67";
    // Generated by the API's canonical builder, including raw BOM/CRLF/Unicode bytes.
    let instructions =
        include_bytes!("../../../tests/fixtures/content-bundle-instructions-v1.tar.gz");
    let instructions_hash = "5644f53789818b6778d665399d5241f33b28fd16231356cc8c930d5109feb35c";
    let root = config.home.bundles_dir();
    tokio::fs::create_dir_all(&root).await.unwrap();
    tokio::fs::write(root.join(format!("{hash}.tar.gz")), archive)
        .await
        .unwrap();
    tokio::fs::write(
        root.join(format!("{instructions_hash}.tar.gz")),
        instructions,
    )
    .await
    .unwrap();
    let mut context = minimal_context();
    let package = serde_json::json!({
        "format": "tar-gzip-v1",
        "instructions": {"sha256":instructions_hash,"archiveBytes":instructions.len(),"downloadUrl":"https://unreachable.invalid/already-cached-instructions"},
        "skills": [{"sha256":hash,"archiveBytes":archive.len(),"downloadUrl":"https://unreachable.invalid/already-cached", "mountPath":"/home/user/.codex/skills/example"}],
    });
    context.content_bundles = serde_json::from_value(package.clone()).unwrap();
    let overrides = Arc::new(MockSandboxOverrides::new());
    let factory = MockSandboxFactory::with_overrides(Arc::clone(&overrides));
    let (mut outcome, _) = execute_job(
        &factory,
        context,
        NewSandboxDispatch {
            id: SandboxId::new_v4(),
            reuse_result: SandboxReuseResult::NoReuseKey,
        },
        &config,
        &default_params(),
        CancellationToken::new(),
    )
    .await;
    assert_eq!(outcome.exit_code(), 0, "{:?}", outcome.error());
    if let Some(report) = outcome.startup_report.take() {
        report.finish().await;
    }
    assert!(
        overrides
            .private_write_files_calls()
            .iter()
            .flat_map(|call| &call.files)
            .any(|file| file.content == archive)
    );
    assert!(
        overrides
            .private_write_files_calls()
            .iter()
            .flat_map(|call| &call.files)
            .any(|file| file.content == instructions)
    );
    assert!(
        overrides
            .exec_calls()
            .iter()
            .any(|call| call.cmd.ends_with(" --bundle-stdin"))
    );
    assert_eq!(overrides.start_agent_process_calls().len(), 1);
    assert!(
        outcome.storage_fingerprints.storages["/home/user/.codex/skills/example"]
            .matches("content-bundle", hash)
    );
    let sandbox = outcome.sandbox.take().unwrap();
    let (idle, _lease) =
        make_reusable_idle_sandbox(sandbox, outcome.source_ip, "test-session").await;
    let mut next_context = minimal_context();
    next_context.run_id = runner_types::ids::RunId::new_v4();
    next_context.content_bundles = serde_json::from_value(package).unwrap();
    let (mut next, _) = execute_job_reuse(
        idle,
        next_context,
        &config,
        &default_params(),
        CancellationToken::new(),
    )
    .await;
    assert_eq!(next.exit_code(), 0, "{:?}", next.error());
    if let Some(report) = next.startup_report.take() {
        report.finish().await;
    }
    assert_eq!(overrides.start_agent_process_calls().len(), 2);
    assert!(
        next.storage_fingerprints.storages["/home/user/.codex/skills/example"]
            .matches("content-bundle", hash)
    );
}
