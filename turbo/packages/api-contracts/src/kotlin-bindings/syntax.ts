export const defaultKotlinPackage = "ai.okou.android.api.generated";

export function kotlinHeader(packageName = defaultKotlinPackage): string {
  if (!/^[a-z][a-z0-9_]*(?:\.[a-z][a-z0-9_]*)*$/u.test(packageName))
    throw new Error("Invalid Kotlin package");
  return `// @generated by @okouai/api-contracts. Do not edit by hand.
// Regenerate: cd turbo && pnpm -F @okouai/api-contracts generate:kotlin
package ${packageName}
`;
}

export function schemaObject(
  value: unknown,
): value is Readonly<Record<string, unknown>> {
  return typeof value === "object" && value !== null && !Array.isArray(value);
}

export function kotlinIdentifier(value: string): string {
  if (!/^[A-Za-z_][A-Za-z0-9_]*$/u.test(value))
    throw new Error(`Invalid Kotlin identifier: ${value}`);
  return `\`${value}\``;
}

export function kotlinTypeName(value: string): string {
  if (!/^[A-Z][A-Za-z0-9]*$/u.test(value))
    throw new Error(`Invalid Kotlin type: ${value}`);
  return value;
}

export function kotlinQuote(value: string): string {
  return JSON.stringify(value).replaceAll("$", "\\$");
}
