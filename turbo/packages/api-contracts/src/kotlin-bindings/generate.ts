import { mkdir, readFile, writeFile } from "node:fs/promises";
import { join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { toJSONSchema, type ZodType } from "zod";
import {
  CLIENT_TYPE_ANDROID,
  CLIENT_TYPE_HEADER,
  CLIENT_VERSION_HEADER,
  CLIENT_SESSION_ID_HEADER,
  CLIENT_REQUEST_ID_HEADER,
} from "../contracts/client-headers";
import { kotlinRouteBindings, kotlinTypeBindings } from "./bindings";
import { kotlinTokens } from "./source-tokens";

export const generatedKotlinRelativeDirectory =
  "android/app/src/main/kotlin/ai/okou/android/api/generated";
const repositoryRoot = fileURLToPath(
  new URL("../../../../../", import.meta.url),
);
const header = `// @generated by @okouai/api-contracts. Do not edit by hand.
// Regenerate: cd turbo && pnpm -F @okouai/api-contracts generate:kotlin
package ai.okou.android.api.generated
`;
type JsonObject = Readonly<Record<string, unknown>>;

function object(value: unknown): value is JsonObject {
  return typeof value === "object" && value !== null && !Array.isArray(value);
}

function identifier(value: string): string {
  if (!/^[A-Za-z_][A-Za-z0-9_]*$/u.test(value))
    throw new Error(`Invalid Kotlin identifier: ${value}`);
  return `\`${value}\``;
}

function typeName(value: string): string {
  if (!/^[A-Z][A-Za-z0-9]*$/u.test(value))
    throw new Error(`Invalid Kotlin type: ${value}`);
  return value;
}

function quote(value: string): string {
  return JSON.stringify(value).replaceAll("$", "\\$");
}

function suffix(value: string): string {
  return value[0]!.toUpperCase() + value.slice(1);
}

function nullableSchema(
  value: JsonObject,
  name: string,
): JsonObject | undefined {
  if (Array.isArray(value.type)) {
    const nonNull = value.type.filter((item) => {
      return item !== "null";
    });
    if (value.type.length === 2 && nonNull.length === 1)
      return { ...value, type: nonNull[0] };
    throw new Error(`${name}: unsupported type union`);
  }
  if (Array.isArray(value.anyOf)) {
    const nonNull = value.anyOf.filter((item) => {
      return !object(item) || item.type !== "null";
    });
    if (value.anyOf.length === 2 && nonNull.length === 1 && object(nonNull[0]))
      return nonNull[0];
    throw new Error(`${name}: unsupported union`);
  }
  return undefined;
}

function renderStringEnum(value: JsonObject, name: string): string | undefined {
  const values: unknown =
    value.enum ?? (typeof value.const === "string" ? [value.const] : undefined);
  if (!Array.isArray(values)) return undefined;
  if (
    values.length === 0 ||
    !values.every((item): item is string => {
      return typeof item === "string";
    })
  )
    throw new Error(`${name}: unsupported enum`);
  const entries = values.map((item) => {
    const entry = item.replaceAll(/[^A-Za-z0-9]+/gu, "_").toUpperCase();
    const symbol = /^[0-9]/u.test(entry) ? `VALUE_${entry}` : entry;
    if (!symbol || !/^[A-Z_][A-Z0-9_]*$/u.test(symbol))
      throw new Error(`${name}: invalid enum name`);
    return { item, symbol };
  });
  if (
    new Set(
      entries.map((entry) => {
        return entry.symbol;
      }),
    ).size !== entries.length
  )
    throw new Error(`${name}: enum name collision`);
  const lines = entries.map(({ item, symbol }) => {
    return `    @SerialName(${quote(item)})\n    ${symbol},`;
  });
  return `@Serializable\nenum class ${name} {\n${lines.join("\n")}\n}`;
}

/** Selected schema emitter. Unsupported constructs must never become untyped JSON. */
export function renderKotlinTypes(
  bindings: readonly {
    readonly name: string;
    readonly schema: ZodType;
    readonly direction: "input" | "output";
  }[] = kotlinTypeBindings,
): string {
  const declarations: string[] = [];
  const names = new Set<string>();
  const render = (value: unknown, name: string): string => {
    if (!object(value)) throw new Error(`${name}: expected a JSON schema`);
    const nullable = nullableSchema(value, name);
    if (nullable) return `${render(nullable, name)}?`;
    if (value.$ref || value.oneOf || value.allOf || Array.isArray(value.type)) {
      throw new Error(`${name}: unsupported schema composition`);
    }
    const enumSource = renderStringEnum(value, name);
    if (enumSource !== undefined) {
      reserve(name);
      declarations.push(enumSource);
      return name;
    }
    switch (value.type) {
      case "string":
        return "String";
      case "boolean":
        return "Boolean";
      case "integer":
        return "Long";
      case "number":
        return "Double";
      case "array":
        return `List<${render(value.items, `${name}Item`)}>`;
      case "object": {
        reserve(name);
        if (
          !object(value.properties) ||
          (value.additionalProperties !== undefined &&
            value.additionalProperties !== false)
        ) {
          throw new Error(`${name}: unsupported object/dictionary`);
        }
        const required = new Set(
          Array.isArray(value.required) ? value.required : [],
        );
        const fields = Object.entries(value.properties).map(
          ([field, schema]) => {
            const wireType = render(schema, `${name}${suffix(field)}`);
            const optional = !required.has(field);
            const propertyType =
              optional && !wireType.endsWith("?") ? `${wireType}?` : wireType;
            return `    val ${identifier(field)}: ${propertyType}${optional ? " = null" : ""},`;
          },
        );
        if (fields.length === 0)
          throw new Error(
            `${name}: empty objects need an explicit wire representation`,
          );
        declarations.push(
          `@Serializable\ndata class ${name}(\n${fields.join("\n")}\n)`,
        );
        return name;
      }
      default:
        throw new Error(
          `${name}: unsupported schema type ${String(value.type)}`,
        );
    }
  };
  function reserve(name: string) {
    typeName(name);
    if (names.has(name))
      throw new Error(`Duplicate Kotlin declaration: ${name}`);
    names.add(name);
  }
  for (const binding of bindings) {
    const result = render(
      toJSONSchema(binding.schema, { io: binding.direction }),
      typeName(binding.name),
    );
    if (result !== binding.name)
      throw new Error(`${binding.name}: root must be an object or enum`);
  }
  return `${header}\nimport kotlinx.serialization.SerialName\nimport kotlinx.serialization.Serializable\n\n${declarations.join("\n\n")}\n`;
}

export function renderKotlinFiles(): ReadonlyMap<string, string> {
  const methods = kotlinRouteBindings.map(
    ({ name, response, request, route }) => {
      if (
        !/^(GET|POST|PUT|PATCH|DELETE)$/u.test(route.method) ||
        !/^\/api\/[A-Za-z0-9/-]+$/u.test(route.path) ||
        route.query ||
        route.pathParams
      ) {
        throw new Error(`${name}: unsupported Retrofit route`);
      }
      if (Boolean(request) !== Boolean(route.body) || !route.responses[200])
        throw new Error(`${name}: unsupported request/response binding`);
      const responseType = kotlinTypeBindings.find((binding) => {
        return binding.name === response;
      });
      const requestType = kotlinTypeBindings.find((binding) => {
        return binding.name === request;
      });
      if (
        !responseType ||
        responseType.schema !== route.responses[200] ||
        responseType.direction !== "output" ||
        (request &&
          (!requestType ||
            requestType.schema !== route.body ||
            requestType.direction !== "input"))
      ) {
        throw new Error(
          `${name}: DTO binding does not match the canonical route schema`,
        );
      }
      const parameters = [
        '@Header("Authorization") token: String',
        ...(request ? [`@Body body: ${typeName(request)}`] : []),
      ];
      return `    @${route.method}(${quote(route.path)})\n    suspend fun ${identifier(name)}(${parameters.join(", ")}): Response<${typeName(response)}>`;
    },
  );
  const constants = {
    CLIENT_TYPE: CLIENT_TYPE_ANDROID,
    TYPE_HEADER: CLIENT_TYPE_HEADER,
    VERSION_HEADER: CLIENT_VERSION_HEADER,
    SESSION_HEADER: CLIENT_SESSION_ID_HEADER,
    REQUEST_HEADER: CLIENT_REQUEST_ID_HEADER,
  };
  const imports = new Set(["retrofit2.Response", "retrofit2.http.Header"]);
  for (const { route, request } of kotlinRouteBindings) {
    imports.add(`retrofit2.http.${route.method}`);
    if (request) imports.add("retrofit2.http.Body");
  }
  const routeImports = [...imports]
    .sort()
    .map((value) => {
      return `import ${value}`;
    })
    .join("\n");
  return new Map([
    ["ApiModels.kt", renderKotlinTypes()],
    [
      "CanonicalApi.kt",
      `${header}\n${routeImports}\n\ninternal interface CanonicalApi {\n${methods.join("\n\n")}\n}\n`,
    ],
    [
      "ApiHeaders.kt",
      `${header}\ninternal object ApiHeaders {\n${Object.entries(constants)
        .map(([name, value]) => {
          return `    const val ${name} = ${quote(value)}`;
        })
        .join("\n")}\n}\n`,
    ],
  ]);
}

export async function checkGeneratedKotlin(
  root = repositoryRoot,
): Promise<string[]> {
  const findings: string[] = [];
  for (const [file, expected] of renderKotlinFiles()) {
    const path = join(generatedKotlinRelativeDirectory, file);
    let actual: string;
    try {
      actual = await readFile(join(root, path), "utf8");
    } catch (error) {
      if (
        !(error instanceof Error) ||
        !("code" in error) ||
        error.code !== "ENOENT"
      )
        throw error;
      findings.push(`${path}: missing generated file`);
      continue;
    }
    const tokens = (source: string) => {
      const parts = kotlinTokens(source);
      return JSON.stringify(
        parts
          .filter((token, index) => {
            return (
              token.text !== "," ||
              ![")", "]", "}"].includes(parts[index + 1]?.text ?? "")
            );
          })
          .map((token) => {
            return token.text;
          }),
      );
    };
    if (tokens(actual) !== tokens(expected))
      findings.push(
        `${path}: generated API drift; run generate:kotlin and Android spotlessApply`,
      );
  }
  return findings;
}

async function main() {
  if (
    process.argv.slice(2).some((arg) => {
      return arg !== "--check";
    })
  )
    throw new Error("Usage: generate.ts [--check]");
  if (process.argv.includes("--check")) {
    const findings = await checkGeneratedKotlin();
    if (findings.length > 0) throw new Error(findings.join("\n"));
    return;
  }
  const directory = join(repositoryRoot, generatedKotlinRelativeDirectory);
  await mkdir(directory, { recursive: true });
  for (const [file, content] of renderKotlinFiles())
    await writeFile(join(directory, file), content);
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href)
  await main();
