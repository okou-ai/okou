const contractsDirectory = fileURLToPath(
  new URL("../contracts/", import.meta.url),
);
const clientDirectory = fileURLToPath(new URL("./", import.meta.url));
const generatedHeader = [
  "// Generated by src/client/generate.ts. Do not edit by hand.",
  "// Regenerate: cd turbo && pnpm -F @okouai/api-contracts generate:client",
  "",
] as const;

export interface ClientContractExport {
  readonly name: string;
  readonly contract: AppRouter;
}

export interface ClientContractModule {
  readonly module: string;
  readonly contracts: readonly ClientContractExport[];
}

function compareNames(left: string, right: string): number {
  return left < right ? -1 : left > right ? 1 : 0;
}

function originalName(name: string): string {
  return `Original${name.replace(/^./, (first) => {
    return first.toUpperCase();
  })}`;
}

function isRecord(value: unknown): value is Record<string, unknown> {
  return typeof value === "object" && value !== null && !Array.isArray(value);
}

function isAppRoute(value: unknown): value is AppRoute {
  return (
    isRecord(value) &&
    (value.method === "GET" ||
      value.method === "POST" ||
      value.method === "PUT" ||
      value.method === "PATCH" ||
      value.method === "DELETE") &&
    typeof value.path === "string" &&
    isRecord(value.responses)
  );
}

function isAppRouter(value: unknown): value is AppRouter {
  if (!isRecord(value)) {
    return false;
  }
  const routes = Object.values(value);
  return routes.length > 0 && routes.every(isAppRoute);
}

function isExported(statement: ts.Statement): boolean {
  return (
    ts.canHaveModifiers(statement) &&
    ts.getModifiers(statement)?.some((modifier) => {
      return modifier.kind === ts.SyntaxKind.ExportKeyword;
    }) === true
  );
}

function runtimeExportNames(source: ts.SourceFile): string[] {
  const names: string[] = [];
  for (const statement of source.statements) {
    if (ts.isVariableStatement(statement) && isExported(statement)) {
      for (const declaration of statement.declarationList.declarations) {
        if (ts.isIdentifier(declaration.name)) {
          names.push(declaration.name.text);
        }
      }
    } else if (
      ts.isExportDeclaration(statement) &&
      !statement.isTypeOnly &&
      statement.moduleSpecifier === undefined &&
      statement.exportClause !== undefined &&
      ts.isNamedExports(statement.exportClause)
    ) {
      for (const element of statement.exportClause.elements) {
        if (!element.isTypeOnly) {
          names.push(element.name.text);
        }
      }
    }
  }
  return [...new Set(names)].sort(compareNames);
}

/** Source contracts are evaluated only by build-time generation and tests. */
export async function discoverClientContractModules({
  sourceDirectory = contractsDirectory,
}: {
  sourceDirectory?: string;
} = {}): Promise<ClientContractModule[]> {
  const entries = (await readdir(sourceDirectory, { withFileTypes: true }))
    .filter((entry) => {
      return (
        entry.isFile() &&
        entry.name.endsWith(".ts") &&
        !entry.name.endsWith(".test.ts") &&
        !entry.name.endsWith(".d.ts")
      );
    })
    .sort((left, right) => {
      return compareNames(left.name, right.name);
    });
  const modules: ClientContractModule[] = [];
  for (const entry of entries) {
    const path = join(sourceDirectory, entry.name);
    const source = ts.createSourceFile(
      path,
      await readFile(path, "utf8"),
      ts.ScriptTarget.Latest,
      true,
      ts.ScriptKind.TS,
    );
    const names = runtimeExportNames(source);
    if (names.length === 0) {
      continue;
    }
    const exports: unknown = await import(pathToFileURL(path).href);
    if (!isRecord(exports)) {
      throw new Error(`Unable to read contract exports from ${path}`);
    }
    const contracts: ClientContractExport[] = [];
    for (const name of names) {
      const contract = exports[name];
      if (isAppRouter(contract)) {
        contracts.push({ name, contract });
      }
    }
    if (contracts.length > 0) {
      modules.push({ module: basename(entry.name, ".ts"), contracts });
    }
  }
  return modules;
}

function renderNamedImport(
  names: readonly string[],
  source: string,
  typeOnly = false,
): string[] {
  const prefix = typeOnly ? "import type" : "import";
  const single = `${prefix} { ${names.join(", ")} } from ${JSON.stringify(source)};`;
  return names.length === 1 || single.length <= 80
    ? [single]
    : [
        `${prefix} {`,
        ...names.map((name) => {
          return `  ${name},`;
        }),
        `} from ${JSON.stringify(source)};`,
      ];
}

function renderRoutes(contract: AppRouter): string[] {
  const lines: string[] = [];
  for (const [name, route] of Object.entries(contract)) {
    const statuses = Object.keys(route.responses)
      .map(Number)
      .sort((left, right) => {
        return left - right;
      });
    lines.push(
      `  ${/^[A-Za-z_$][\w$]*$/.test(name) ? name : JSON.stringify(name)}: {`,
      `    method: ${JSON.stringify(route.method)},`,
      `    path: ${JSON.stringify(route.path)},`,
    );
    if (route.contentType !== undefined) {
      lines.push(`    contentType: ${JSON.stringify(route.contentType)},`);
    }
    lines.push("    statuses: {");
    for (const status of statuses) {
      lines.push(`      ${String(status)}: true,`);
    }
    lines.push("    },", "  },");
  }
  return lines;
}

export function renderClientDescriptorModule({
  module,
  contracts,
}: ClientContractModule): string {
  const lines = [
    ...generatedHeader,
    ...renderNamedImport(
      contracts.map(({ name }) => {
        return `${name} as ${originalName(name)}`;
      }),
      `../contracts/${module}`,
      true,
    ),
    'import type { ClientDescriptor } from "./types";',
    "",
  ];
  for (const { name, contract } of contracts) {
    const assignment = `export const ${name}: ClientDescriptor<typeof ${originalName(name)}> =`;
    const wrappedObject = assignment.length <= 80 && assignment.length + 2 > 80;
    lines.push(
      ...(assignment.length + 2 <= 80
        ? [`${assignment} {`]
        : wrappedObject
          ? [assignment, "  {"]
          : [
              `export const ${name}: ClientDescriptor<`,
              `  typeof ${originalName(name)}`,
              "> = {",
            ]),
      ...renderRoutes(contract).map((line) => {
        return wrappedObject ? `  ${line}` : line;
      }),
      wrappedObject ? "  };" : "};",
      "",
    );
  }
  return lines.join("\n");
}

/** Kept for callers of the original agents-only generation API. */
export function renderAgentsClientDescriptors(): string {
  return renderClientDescriptorModule({
    module: "agents",
    contracts: [
      {
        name: "agentInstructionsContract",
        contract: agentInstructionsContract,
      },
      { name: "agentsByIdContract", contract: agentsByIdContract },
      { name: "agentsMainContract", contract: agentsMainContract },
    ],
  });
}

export function renderClientDescriptorManifest(
  modules: readonly ClientContractModule[],
): string {
  return [
    ...generatedHeader,
    "export const clientDescriptorManifest = [",
    ...modules.flatMap(({ module, contracts }) => {
      const single = `    contracts: [${contracts
        .map(({ name }) => {
          return JSON.stringify(name);
        })
        .join(", ")}],`;
      return [
        "  {",
        `    module: ${JSON.stringify(module)},`,
        ...(single.length <= 80
          ? [single]
          : [
              "    contracts: [",
              ...contracts.map(({ name }) => {
                return `      ${JSON.stringify(name)},`;
              }),
              "    ],",
            ]),
        "  },",
      ];
    }),
    "] as const;",
    "",
  ].join("\n");
}

export function renderClientContractImportManifest(
  modules: readonly ClientContractImportModule[],
): string {
  if (modules.length === 0) {
    return [
      ...generatedHeader,
      "export const clientContractImportManifest = [] as const;",
      "",
    ].join("\n");
  }
  return [
    ...generatedHeader,
    "export const clientContractImportManifest = [",
    ...modules.flatMap(({ module, contracts, bindings }) => {
      const single = `    contracts: [${contracts
        .map((name) => {
          return JSON.stringify(name);
        })
        .join(", ")}],`;
      return [
        "  {",
        `    module: ${JSON.stringify(module)},`,
        ...(single.length <= 80
          ? [single]
          : [
              "    contracts: [",
              ...contracts.map((name) => {
                return `      ${JSON.stringify(name)},`;
              }),
              "    ],",
            ]),
        ...(bindings.length === 0
          ? ["    bindings: [],"]
          : [
              "    bindings: [",
              ...bindings.flatMap(({ name, source, imported }) => {
                return [
                  "      {",
                  `        name: ${JSON.stringify(name)},`,
                  `        source: ${JSON.stringify(source)},`,
                  `        imported: ${JSON.stringify(imported)},`,
                  "      },",
                ];
              }),
              "    ],",
            ]),
        "  },",
      ];
    }),
    "] as const;",
    "",
  ].join("\n");
}

export function renderClientDescriptorTestingRegistry(
  modules: readonly ClientContractModule[],
): string {
  const lines = [
    ...generatedHeader,
    "// Test-only schema registry. Never import this module in production.",
    "",
    'import type { AppRouter } from "../contracts/trpc-contract";',
    'import type { ClientRouter } from "./types";',
  ];
  for (const { module, contracts } of modules) {
    lines.push(
      ...renderNamedImport(
        contracts.map(({ name }) => {
          return `${name} as ${originalName(name)}`;
        }),
        `../contracts/${module}`,
      ),
      ...renderNamedImport(
        contracts.map(({ name }) => {
          return name;
        }),
        `./${module}`,
      ),
    );
  }
  lines.push(
    "",
    "export const clientDescriptorContracts: readonly (readonly [",
    "  ClientRouter,",
    "  AppRouter,",
    "])[] = [",
    ...modules.flatMap(({ contracts }) => {
      return contracts.flatMap(({ name }) => {
        const single = `  [${name}, ${originalName(name)}],`;
        return single.length <= 80
          ? [single]
          : ["  [", `    ${name},`, `    ${originalName(name)},`, "  ],"];
      });
    }),
    "];",
    "",
  );
  return lines.join("\n");
}

async function readGeneratedFile(path: string): Promise<string | undefined> {
  try {
    return await readFile(path, "utf8");
  } catch (error) {
    if (error instanceof Error && "code" in error && error.code === "ENOENT") {
      return undefined;
    }
    throw error;
  }
}

async function findObsoleteGeneratedFiles(
  outputDirectory: string,
  expectedPaths: ReadonlySet<string>,
): Promise<string[]> {
  const entries = await readdir(outputDirectory, {
    withFileTypes: true,
  }).catch((error: unknown) => {
    if (error instanceof Error && "code" in error && error.code === "ENOENT") {
      return [];
    }
    throw error;
  });
  const obsolete: string[] = [];
  for (const entry of entries) {
    const path = join(outputDirectory, entry.name);
    if (
      entry.isFile() &&
      entry.name.endsWith(".ts") &&
      !expectedPaths.has(path)
    ) {
      const current = await readGeneratedFile(path);
      if (current?.startsWith(generatedHeader[0])) {
        obsolete.push(path);
      }
    }
  }
  return obsolete;
}

export async function generateClientDescriptors({
  check = false,
  outputDirectory = clientDirectory,
  sourceDirectory = contractsDirectory,
  outputPath,
}: {
  check?: boolean;
  outputDirectory?: string;
  sourceDirectory?: string;
  /** Legacy agents-only fixture output. Default generation always covers all modules. */
  outputPath?: string;
} = {}): Promise<void> {
  const modules = outputPath
    ? []
    : await discoverClientContractModules({ sourceDirectory });
  const outputs: readonly (readonly [string, string])[] = outputPath
    ? [[outputPath, renderAgentsClientDescriptors()]]
    : [
        ...modules.map((module) => {
          return [
            join(outputDirectory, `${module.module}.ts`),
            renderClientDescriptorModule(module),
          ] as const;
        }),
        [
          join(outputDirectory, "manifest.ts"),
          renderClientDescriptorManifest(modules),
        ],
        [
          join(outputDirectory, "testing.ts"),
          renderClientDescriptorTestingRegistry(modules),
        ],
        [
          join(outputDirectory, "imports.ts"),
          renderClientContractImportManifest(
            await discoverClientContractImportModules({
              modules,
              sourceDirectory,
            }),
          ),
        ],
      ];
  const stale: string[] = [];
  for (const [path, expected] of outputs) {
    if ((await readGeneratedFile(path)) !== expected) {
      stale.push(path);
    }
  }
  const obsolete = outputPath
    ? []
    : await findObsoleteGeneratedFiles(
        outputDirectory,
        new Set(
          outputs.map(([path]) => {
            return path;
          }),
        ),
      );
  if (check && (stale.length > 0 || obsolete.length > 0)) {
    throw new Error(
      `Generated client descriptors are out of date (${[...stale, ...obsolete]
        .map((path) => {
          return basename(path);
        })
        .join(
          ", ",
        )}). Run pnpm -F @okouai/api-contracts generate:client from turbo/.`,
    );
  }
  if (!check) {
    await mkdir(outputPath ? dirname(outputPath) : outputDirectory, {
      recursive: true,
    });
    for (const [path, expected] of outputs) {
      if (stale.includes(path)) {
        await writeFile(path, expected);
      }
    }
    for (const path of obsolete) {
      await rm(path);
    }
  }
}

function isMainModule(): boolean {
  const entrypoint = process.argv[1];
  return (
    entrypoint !== undefined &&
    import.meta.url === pathToFileURL(entrypoint).href
  );
}

async function main(): Promise<void> {
  const args = process.argv.slice(2);
  if (args.length > 1 || (args.length === 1 && args[0] !== "--check")) {
    throw new Error("Usage: generate:client [--check]");
  }
  await generateClientDescriptors({ check: args[0] === "--check" });
}

if (isMainModule()) {
  await main().catch((error: unknown) => {
    console.error(error instanceof Error ? error.message : error);
    process.exitCode = 1;
  });
}
