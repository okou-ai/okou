import { expect, test } from "vitest";
import { navigationAddress } from "../input/address.ts";

test.each([
  [" example.com ", "http://example.com/"],
  ["www.example.com:8080/a?b=1#c", "http://www.example.com:8080/a?b=1#c"],
  ["example.test:80/path", "http://example.test/path"],
  [
    "example.test/a b?q=hello world#part",
    "http://example.test/a%20b?q=hello%20world#part",
  ],
  ["例子.测试/你好", "http://xn--fsqu00a.xn--0zwm56d/%E4%BD%A0%E5%A5%BD"],
  ["localhost", "http://localhost/"],
  ["LOCALHOST:3000/", "http://localhost:3000/"],
  ["app.localhost/path", "http://app.localhost/path"],
  ["127.0.0.1:8080/path?x#y", "http://127.0.0.1:8080/path?x#y"],
  ["192.168.0.10/", "http://192.168.0.10/"],
  ["[::1]:8080/path?x#y", "http://[::1]:8080/path?x#y"],
  ["[2001:db8::1]/", "http://[2001:db8::1]/"],
  ["printer:3000/status", "http://printer:3000/status"],
  ["//example.test/path", "http://example.test/path"],
  ["//printer/status", "http://printer/status"],
  ["https://EXAMPLE.test:443/a?b#c", "https://example.test/a?b#c"],
  ["http://printer/path", "http://printer/path"],
  ["about:blank", "about:blank"],
  ["data:text/plain,hello world", "data:text/plain,hello world"],
  ["file:///tmp/fixture.html", "file:///tmp/fixture.html"],
  ["chrome://version/", "chrome://version/"],
  ["view-source:https://example.test/", "view-source:https://example.test/"],
  [
    "javascript:document.title='fixture';void 0",
    "javascript:document.title='fixture';void 0",
  ],
  ["mailto:fixture@example.test", "mailto:fixture@example.test"],
  ["custom:payload", "custom:payload"],
  ["custom.scheme://host/path", "custom.scheme://host/path"],
])("prepares submitted address %s", (input, expected) => {
  expect(navigationAddress(input)).toBe(expected);
});

test.each([
  "",
  "   ",
  "hello",
  "find some text",
  "search example.test",
  "search example.test/path",
  "/relative",
  "./relative",
  "../relative",
  "?query",
  "#fragment",
  "///relative",
  "123",
  "1.2",
  "127.1",
  "0x7f000001",
  "0x7f.0.0.1",
  "999.0.0.1",
  "::1",
  "[::1",
  "localhost:invalid",
  "localhost:65536",
  "example.test:invalid",
  "example.test:65536",
  "printer:65536",
  ".example.test",
  "example..test",
  "fixture@example.test",
  "//fixture:secret@example.test/",
  "https://",
  String.raw`example.test\path`,
  "example.\ntest/",
  "https://example.\ttest/",
  "data:text/plain,embedded\u0000control",
])("rejects invalid or search-like input %s without a search", (input) => {
  expect(navigationAddress(input)).toBeNull();
});
