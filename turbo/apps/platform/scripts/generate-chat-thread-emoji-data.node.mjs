import assert from "node:assert/strict";
import { createHash } from "node:crypto";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import process from "node:process";
import { URL } from "node:url";

import emojiGroups from "unicode-emoji-json/data-by-group.json" with { type: "json" };

async function main() {
  const outputUrl = new URL(
    "../src/data/chat-thread-emoji.json",
    import.meta.url,
  );
  const generatedGroups = emojiGroups.map((group) => {
    return {
      name: group.name,
      emojis: group.emojis.map((entry) => {
        return { emoji: entry.emoji, name: entry.name };
      }),
    };
  });
  const generatedJson = `${JSON.stringify(generatedGroups, null, 2)}\n`;
  const contentHash = createHash("sha256")
    .update(generatedJson)
    .digest("hex")
    .slice(0, 12);
  const urlModuleUrl = new URL(
    "../src/data/chat-thread-emoji-url.ts",
    import.meta.url,
  );
  const generatedUrlModule = `// Generated by scripts/generate-chat-thread-emoji-data.node.mjs. Do not edit.
import { platformStaticAssetUrl } from "../lib/static-assets.ts";

export const chatThreadEmojiDataUrl = platformStaticAssetUrl(
  "data/chat-thread-emoji-${contentHash}.json",
);
`;

  if (process.argv.includes("--check")) {
    const committedJson = await readFile(outputUrl, "utf8");
    assert.equal(
      committedJson,
      generatedJson,
      "chat-thread-emoji.json is stale; run pnpm generate:emoji-data",
    );
    const committedUrlModule = await readFile(urlModuleUrl, "utf8");
    assert.equal(
      committedUrlModule,
      generatedUrlModule,
      "chat-thread-emoji-url.ts is stale; run pnpm generate:emoji-data and publish the new content-hashed asset before updating the App",
    );
  } else {
    await mkdir(new URL("../src/data/", import.meta.url), { recursive: true });
    await writeFile(outputUrl, generatedJson);
    await writeFile(urlModuleUrl, generatedUrlModule);
  }
}

await main();
