#!/usr/bin/env python3
"""Sync the Web-pinned Lucide vectors into the native template asset catalog."""

import argparse
import base64
import hashlib
import io
import json
import re
import subprocess
import tarfile
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SYSTEM = ROOT / "ios/Okou/DesignSystem"
ASSETS = ROOT / "ios/Okou/Resources/Assets.xcassets"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--archive", type=Path, help="Use a locally cached official npm archive")
    args = parser.parse_args()
    manifest = json.loads((SYSTEM / "icons.json").read_text())
    version = manifest["version"]
    stroke = manifest["strokeWidth"]
    intrinsic = manifest["intrinsicSize"]
    if intrinsic != 20:
        parser.error("Review intrinsic menu sizing against native controls before changing it")
    if stroke not in (1.5, 2):
        parser.error("Choose an explicit native Lucide stroke width")
    for package in ("turbo/packages/ui/package.json", "turbo/apps/platform/package.json"):
        actual = json.loads((ROOT / package).read_text())["dependencies"]["lucide-react"]
        if actual != version:
            parser.error(f"{package} uses {actual}; update the mobile icon manifest deliberately")
    if args.archive:
        data = args.archive.read_bytes()
    else:
        url = f"https://registry.npmjs.org/lucide-static/-/lucide-static-{version}.tgz"
        with urllib.request.urlopen(url, timeout=30) as response:
            data = response.read()
    integrity = "sha512-" + base64.b64encode(hashlib.sha512(data).digest()).decode()
    if integrity != manifest["integrity"]:
        parser.error("Lucide archive integrity mismatch")
    names = sorted(set(manifest["icons"]))
    optical_scales = manifest.get("opticalScales", {})
    if not set(optical_scales).issubset(names):
        parser.error("Optical corrections must reference registered icons")
    metrics = (SYSTEM / "OkouMetrics.swift").read_text()
    menu_size = float(re.search(r"static let menu: CGFloat = ([0-9.]+)", metrics)[1])
    if intrinsic != menu_size:
        parser.error("Compiled image intrinsic size must match the native menu token")
    files = {}
    with tarfile.open(fileobj=io.BytesIO(data), mode="r:gz") as archive:
        for name in names:
            svg = archive.extractfile(f"package/icons/{name}.svg").read().decode()
            # Native optical weight is independent of Web geometry; keep canonical Lucide paths.
            svg = svg.replace('stroke="currentColor"', 'stroke="black"')
            svg = svg.replace('stroke-width="2"', f'stroke-width="{stroke}"')
            # Native menus consume UIImage.size, ignoring a SwiftUI frame. Keep
            # the canonical 24-unit paths but ship a native menu-sized image.
            svg = svg.replace('width="24"', f'width="{intrinsic}"')
            svg = svg.replace('height="24"', f'height="{intrinsic}"')
            scale = optical_scales.get(name, 1)
            if not 0.5 <= scale <= 1:
                parser.error(f"Review invalid optical scale for {name}")
            if scale != 1:
                offset = 12 * (1 - scale)
                group = f'<g transform="translate({offset:g} {offset:g}) scale({scale:g})">'
                svg = re.sub(r"(<svg\b[\s\S]*?>)([\s\S]*?)(</svg>)",
                             lambda match: match[1] + group + match[2] + "</g>" + match[3], svg)
            directory = ASSETS / f"Lucide-{name}.imageset"
            files[directory / "icon.svg"] = svg
            files[directory / "Contents.json"] = json.dumps({
                "images": [{"filename": "icon.svg", "idiom": "universal"}],
                "info": {"author": "xcode", "version": 1},
                "properties": {"preserves-vector-representation": True,
                               "template-rendering-intent": "template"},
            }, indent=2) + "\n"
        files[SYSTEM / "Lucide-LICENSE.txt"] = archive.extractfile("package/LICENSE").read().decode()
    lines = [
        "// Generated by ios/scripts/sync-design-assets.py. Do not edit by hand.",
        f"// Lucide {version}; stroke: {stroke}, viewBox: 24 units, intrinsic: {intrinsic} pt.",
        "enum OkouIconAssets {", "  static let names: [String] = [",
        *[f'    "{name}",' for name in names], "  ]",
        "}", "",
    ]
    files[SYSTEM / "OkouIconAssets.generated.swift"] = subprocess.run(
        ["xcrun", "swift-format", "format"], input="\n".join(lines),
        capture_output=True, text=True, check=True).stdout
    stale = []
    for path, content in files.items():
        if not path.exists() or path.read_text() != content:
            stale.append(str(path.relative_to(ROOT)))
            if not args.check:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(content)
    expected = {f"Lucide-{name}.imageset" for name in names}
    for directory in ASSETS.glob("Lucide-*.imageset"):
        if directory.name not in expected:
            parser.error(f"Remove unregistered icon asset: {directory.name}")
    if args.check and stale:
        parser.exit(1, "Mobile assets have drifted:\n" + "\n".join(stale) + "\n")
    print(f"{'Checked' if args.check else 'Synced'} {len(names)} Lucide {version} template vectors.")


if __name__ == "__main__":
    main()
