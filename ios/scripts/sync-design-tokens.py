#!/usr/bin/env python3
"""Generate native light/dark colors from the Web design system, without CSS dependencies."""

import argparse
import colorsys
import json
import re
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "turbo/packages/ui/src/styles/globals.css"
OUTPUT = ROOT / "ios/Okou/DesignSystem/Foundations/OkouColor.generated.swift"


def block(source, selector):
    start = source.index(selector) + len(selector)
    end = source.index("}", start)
    return dict(re.findall(r"--([\w-]+)\s*:\s*([^;]+);", source[start:end]))


def rgba(name, variables, seen=()):
    if name in seen:
        raise ValueError(f"Cyclic color: {name}")
    value = variables[name].strip()
    reference = re.fullmatch(r"(?:hsl\(\s*)?var\(\s*--([\w-]+)\s*\)\s*\)?", value)
    if reference:
        return rgba(reference[1], variables, (*seen, name))
    match = re.fullmatch(r"([\d.]+)\s+([\d.]+)%\s+([\d.]+)%(?:\s*/\s*([\d.]+)%?)?", value)
    if not match:
        raise ValueError(f"Unsupported color {name}: {value}")
    hue, saturation, lightness = (float(match[i]) for i in (1, 2, 3))
    red, green, blue = colorsys.hls_to_rgb(hue / 360, lightness / 100, saturation / 100)
    alpha = float(match[4]) / (100 if value.endswith("%") else 1) if match[4] else 1
    return (red, green, blue, alpha)


def color_expression(expression, variables):
    expression = re.sub(r"\s+", " ", expression).strip().replace("hsl( ", "hsl(").replace(" )", ")")
    reference = re.fullmatch(r"hsl\(var\(--([\w-]+)\)(?:\s*/\s*var\(--([\w-]+)\))?\)", expression)
    if reference:
        color = rgba(reference[1], variables)
        if reference[2]:
            alpha = variables[reference[2]]
            return (*color[:3], float(alpha.rstrip("%")) / (100 if alpha.endswith("%") else 1))
        return color
    # Web's filled-state colors mix in sRGB, not HSL or the native display space.
    mix = re.fullmatch(
        r"color-mix\(\s*in srgb,\s*hsl\(var\(--([\w-]+)\)\),\s*hsl\(var\(--([\w-]+)\)\)\s*var\(--([\w-]+)\)\s*\)", expression)
    if mix:
        a, b = rgba(mix[1], variables), rgba(mix[2], variables)
        fraction = float(variables[mix[3]].rstrip("%")) / 100
        return tuple(x * (1 - fraction) + y * fraction for x, y in zip(a, b))
    raise ValueError(f"Unsupported exported color: {expression}")


def camel(name):
    first, *rest = name.split("-")
    return first + "".join(part.title() for part in rest)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail when generated files have drifted")
    args = parser.parse_args()
    css = re.sub(r"/\*.*?\*/", "", SOURCE.read_text(), flags=re.S)
    light = block(css, "  :root {")
    dark = light | block(css, '  [data-theme="dark"] {')
    bindings = {key.removeprefix("color-"): value for key, value in block(css, "@theme {").items() if key.startswith("color-")}
    # App publishes this alias in addition to shared UI's exports.
    app_css = re.sub(r"/\*.*?\*/", "", (ROOT / "turbo/apps/platform/src/views/css/index.css").read_text(), flags=re.S)
    bindings["sidebar-border"] = block(app_css, "@theme {")["color-sidebar-border"]
    bindings["state-layer"] = "hsl(var(--state-layer))"
    names = sorted(bindings)
    lines = [
        "// Generated by ios/scripts/sync-design-tokens.py. Do not edit by hand.",
        "// Source: turbo/packages/ui/src/styles/globals.css (default palette, light/dark).",
        "import SwiftUI", "import UIKit", "", "enum OkouColor {",
    ]
    for name in sorted(names):
        a = color_expression(bindings[name], light)
        b = color_expression(bindings[name], dark)
        values = ", ".join(f"{v:.8f}" for v in (*a, *b))
        lines += [f"  /// Web: --color-{name}", f"  static let {camel(name)} = adaptive({values})"]
    lines += [
        "", "  private static func adaptive(",
        "    _ lr: Double, _ lg: Double, _ lb: Double, _ la: Double,",
        "    _ dr: Double, _ dg: Double, _ db: Double, _ da: Double",
        "  ) -> Color {",
        "    Color(uiColor: UIColor { traits in",
        "      traits.userInterfaceStyle == .dark",
        "        ? UIColor(red: dr, green: dg, blue: db, alpha: da)",
        "        : UIColor(red: lr, green: lg, blue: lb, alpha: la)",
        "    })", "  }", "}", "",
    ]
    formatted = subprocess.run(
        ["xcrun", "swift-format", "format"], input="\n".join(lines),
        capture_output=True, text=True, check=True).stdout
    files = {OUTPUT: formatted}
    assets = {"AccentColor": "brand-text", "SignInPrimary": "brand-text", "SignInCard": "card", "StartupBackground": "background"}
    for asset, token in assets.items():
        colors = []
        for scheme, variables in (("light", light), ("dark", dark)):
            components = dict(zip(("red", "green", "blue", "alpha"), (f"{v:.8f}" for v in rgba(token, variables))))
            color = {"idiom": "universal", "color": {"color-space": "srgb", "components": components}}
            if scheme == "dark":
                color["appearances"] = [{"appearance": "luminosity", "value": "dark"}]
            colors.append(color)
        path = ROOT / f"ios/Okou/Resources/Assets.xcassets/{asset}.colorset/Contents.json"
        files[path] = json.dumps({"colors": colors, "info": {"author": "xcode", "version": 1}}, indent=2) + "\n"
    stale = []
    for path, content in files.items():
        if not path.exists() or path.read_text() != content:
            stale.append(str(path.relative_to(ROOT)))
            if not args.check:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(content)
    if args.check and stale:
        parser.exit(1, "Design tokens are out of date:\n" + "\n".join(stale) + "\n")
    print(f"{'Checked' if args.check else 'Mapped'} {len(names)} Web color tokens in both appearances and {len(assets)} asset aliases.")


if __name__ == "__main__":
    main()
