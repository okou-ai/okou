#!/usr/bin/env python3
"""Bundle the same versioned avatar layers used by Web; --check is offline."""
import argparse
from concurrent.futures import ThreadPoolExecutor, as_completed
import hashlib
import itertools
import json
from pathlib import Path
import re
import subprocess
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[2]
CORE = ROOT / "turbo/packages/core/src/agent-avatar.ts"
ASSETS = ROOT / "ios/Okou/Resources/Assets.xcassets"
SYSTEM = ROOT / "ios/Okou/DesignSystem"
MANIFEST = SYSTEM / "agent-avatars.json"
SWIFT = SYSTEM / "OkouAvatarAssets.generated.swift"

def authority():
    source = CORE.read_text()
    version = re.search(r'AVATAR_COMPOSER_ASSET_VERSION = "([^"]+)"', source)[1]
    fields = {}
    for name, key in [("FACE_SHAPES", "faces"), ("HAIR_STYLES", "hairs"), ("EXPRESSIONS", "expressions"), ("SKIN_TONES", "skins"), ("HAIR_COLORS", "hairColors"), ("SWEATER_COLORS", "sweaters")]:
        body = re.search(r"AVATAR_COMPOSER_" + name + r" = \[(.*?)\] as const", source, re.S)[1]
        fields[key] = re.findall(r'"([^"]+)"', body)
    return version, fields

def asset_name(path):
    return "AgentAvatar-" + path.removesuffix(".svg").replace("/", "-")

def files(fields):
    paths = []
    for face, hair, color, layer in itertools.product(fields["faces"], fields["hairs"], fields["hairColors"], ["rear", "front"]):
        paths.append(f"hairs/{face}/{hair}-{color}-{layer}.svg")
    paths += [f"faces/{face}-{skin}.svg" for face, skin in itertools.product(fields["faces"], fields["skins"])]
    for face, expression in itertools.product(fields["faces"], fields["expressions"]):
        paths += [f"expressions/{expression}-{face}{suffix}.svg" for suffix in (["-" + skin for skin in fields["skins"]] if expression == "calm" else [""])]
    paths += [f"neck/{skin}.svg" for skin in fields["skins"]]
    paths += [f"sweater/{color}.svg" for color in fields["sweaters"]]
    legacy = [f"head-r{r}-s{s}.svg" for r, s in itertools.product(range(1, 6), range(5))]
    legacy += [f"hair-r{r}-h{h}-c{c}.svg" for r, h, c in itertools.product(range(1, 6), range(1, 6), range(1, 6))]
    legacy += [f"face-r{r}-f{f}-{i}.svg" for r, f, i in itertools.product(range(1, 6), range(1, 6), "dmh")]
    return sorted(paths), sorted(legacy)

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    version, fields = authority()
    current, legacy = files(fields)
    base = f"https://static.vm0.io/platform/views/zero-page/assets/avatar-svg-v2/{version}/"
    old = "https://static.vm0.io/platform/views/zero-page/assets/avatar-svg/"
    expected = [(path, base + path) for path in current] + [(path, old + path) for path in legacy]
    swift = "// Generated by ios/scripts/sync-agent-avatars.py. Do not edit.\nimport Foundation\n\nenum OkouAvatarAssets {\n"
    swift += f'  static let version = "{version}"\n'
    swift += f'  static let baseURL = "{base}avatar.svg"\n'
    for key, values in fields.items():
        swift += f"  static let {key}: [String] = " + json.dumps(values) + "\n"
    swift += "  static let names: [String] = [\n" + "".join(f'    "{asset_name(path)}",\n' for path, _ in expected) + "  ]\n}\n"
    # Use the same formatter as ordinary Swift sources for deterministic checks.
    swift = subprocess.run(["xcrun", "swift-format", "format"], input=swift, capture_output=True, text=True, check=True).stdout
    previous = json.loads(MANIFEST.read_text()) if MANIFEST.exists() else {}
    if args.check:
        assert SWIFT.read_text() == swift, "Avatar config changed; resync assets"
        assert previous["version"] == version
        assert {item["path"] for item in previous["layers"]} == {path for path, _ in expected}
        for item in previous["layers"]:
            data = (ASSETS / (asset_name(item["path"]) + ".imageset") / "layer.svg").read_bytes()
            assert hashlib.sha256(data).hexdigest() == item["sha256"], item["path"]
        print(f"Verified {len(expected)} Web avatar layers and composer configuration.")
        return
    known = {item["url"]: item for item in previous.get("layers", [])}
    def fetch(item):
        path, url = item
        target = ASSETS / (asset_name(path) + ".imageset")
        image = target / "layer.svg"
        if url in known and image.exists() and hashlib.sha256(image.read_bytes()).hexdigest() == known[url]["sha256"]:
            return known[url]
        data = subprocess.run(["curl", "--http1.1", "--fail", "--silent", "--show-error", "--location", "--max-time", "20", "--retry", "3", url], capture_output=True, check=True).stdout
        assert ET.fromstring(data).tag.endswith("svg"), url
        target.mkdir(exist_ok=True)
        image.write_bytes(data)
        (target / "Contents.json").write_text(json.dumps({"images": [{"filename": "layer.svg", "idiom": "universal"}], "info": {"author": "xcode", "version": 1}, "properties": {"preserves-vector-representation": True}}, indent=2) + "\n")
        return {"path": path, "url": url, "sha256": hashlib.sha256(data).hexdigest()}
    layers, failures = [], []
    with ThreadPoolExecutor(max_workers=12) as pool:
        futures = {pool.submit(fetch, item): item for item in expected}
        for future in as_completed(futures):
            try:
                layers.append(future.result())
            except Exception as error:
                failures.append(f"{futures[future][1]}: {error}")
    layers.sort(key=lambda item: item["path"])

    MANIFEST.write_text(json.dumps({"version": version, "source": str(CORE.relative_to(ROOT)), "layers": layers}, indent=2) + "\n")
    if failures:
        raise RuntimeError("Avatar download failed; rerun to resume:\n" + "\n".join(failures))
    SWIFT.write_text(swift)
    print(f"Bundled {len(layers)} official Web avatar layers.")

if __name__ == "__main__":
    main()
