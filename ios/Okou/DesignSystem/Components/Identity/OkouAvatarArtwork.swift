enum OkouAvatarSide: String, CaseIterable, Sendable {
  case left, right
}

extension OkouAvatarNode {
  var children: [OkouAvatarNode] {
    get {
      if case .group(let children) = content { return children }
      return []
    }
    set { content = .group(newValue) }
  }

  /// Changes the node with `id`, wherever it is below.
  mutating func update(_ id: String, _ change: (inout OkouAvatarNode) -> Void) {
    if self.id == id {
      change(&self)
      return
    }
    guard case .group(var children) = content else { return }
    for index in children.indices {
      children[index].update(id, change)
    }
    content = .group(children)
  }

  /// Puts the node with `id` inside a new group moved by `transform`, as Web's `wrapIn` does.
  mutating func wrap(_ id: String, in transform: CGAffineTransform) {
    guard case .group(var children) = content else { return }
    for index in children.indices {
      if children[index].id == id {
        children[index] = OkouAvatarArtwork.group(nil, transform: transform, [children[index]])
      } else {
        children[index].wrap(id, in: transform)
      }
    }
    content = .group(children)
  }

  /// Web's `markLines`: every stroked shape below keeps one on-screen weight.
  mutating func markLines() {
    switch content {
    case .group(var children):
      for index in children.indices { children[index].markLines() }
      content = .group(children)
    case .shape(var shape):
      if shape.stroke != nil { shape.isLine = true }
      content = .shape(shape)
    }
  }
}
