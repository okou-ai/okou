import SwiftUI

/// One node of the Okou avatar's drawing, as Web's rig sees its SVG: groups the rig moves and
/// shapes it shows, hides or reshapes, each found by the id Web gives it.
struct OkouAvatarNode: Sendable {
  enum Content: Sendable {
    case group([OkouAvatarNode])
    case shape(OkouAvatarShape)
  }

  /// A clip on the node: a fixed outline, or the shape the rig redraws under that id.
  enum Clip: Sendable {
    case outline(Path)
    case shape(String)
  }

  var id: String?
  var transform = CGAffineTransform.identity
  var opacity: Double = 1
  var clip: Clip?
  var content: Content
}

struct OkouAvatarShape: Sendable {
  var path: Path
  var fill: Color?
  var stroke: Color?
  var width: CGFloat = 1
  var cap: CGLineCap = .butt
  var join: CGLineJoin = .miter
  /// A facial line, Web's `vector-effect: non-scaling-stroke`: it keeps one on-screen weight
  /// through squash and stretch.
  var isLine = false
}

/// Web's Okou avatar artwork (`okou-avatar-artwork.ts`) with the overlays its rig adds
/// (`okou-avatar-rig.ts`, `buildTemplate`): the base drawing is generated by
/// `ios/scripts/sync-okou-avatar.py`; the overlays and their placement are ported here.
enum OkouAvatarArtwork {
  /// The artwork's own coordinate space: a 217-unit square.
  static let view: CGFloat = 217
  /// Line weight of every outline, in artwork units.
  static let line: CGFloat = 2.89154
  /// Web's pose amplitudes are in the legacy 0.41-scale art; the head turns about its chin.
  static let unit: CGFloat = 0.41
  static let head = CGPoint(x: 108.432, y: 180.721)

  /// The drawing the rig poses, built once.
  static let scene = makeScene()

  // MARK: - Builders, shared with the generated artwork

  static func group(
    _ id: String?, transform: CGAffineTransform = .identity, opacity: Double = 1,
    clip: String? = nil, _ children: [OkouAvatarNode]
  ) -> OkouAvatarNode {
    OkouAvatarNode(
      id: id, transform: transform, opacity: opacity,
      clip: clip.map { .outline(Path(okouSVG: $0)) }, content: .group(children))
  }

  static func shape(
    _ id: String?, _ path: Path, fill: Color? = nil, stroke: Color? = nil, width: CGFloat = 1,
    cap: CGLineCap = .butt, join: CGLineJoin = .miter, opacity: Double = 1
  ) -> OkouAvatarNode {
    OkouAvatarNode(
      id: id, opacity: opacity,
      content: .shape(
        OkouAvatarShape(
          path: path, fill: fill, stroke: stroke, width: width, cap: cap, join: join)))
  }

  static func shape(
    _ id: String?, _ data: String, fill: Color? = nil, stroke: Color? = nil, width: CGFloat = 1,
    cap: CGLineCap = .butt, join: CGLineJoin = .miter, opacity: Double = 1
  ) -> OkouAvatarNode {
    shape(
      id, Path(okouSVG: data), fill: fill, stroke: stroke, width: width, cap: cap, join: join,
      opacity: opacity)
  }

  static func ellipse(_ cx: CGFloat, _ cy: CGFloat, _ rx: CGFloat, _ ry: CGFloat) -> Path {
    Path(ellipseIn: CGRect(x: cx - rx, y: cy - ry, width: 2 * rx, height: 2 * ry))
  }

  /// A brand fill as Web's artwork paints it, in Display P3.
  static func p3(_ red: Double, _ green: Double, _ blue: Double) -> Color {
    Color(.displayP3, red: red, green: green, blue: blue)
  }

  static func hex(_ value: UInt32) -> Color {
    Color(
      .sRGB, red: Double((value >> 16) & 0xFF) / 255, green: Double((value >> 8) & 0xFF) / 255,
      blue: Double(value & 0xFF) / 255)
  }

  // MARK: - Transforms, in SVG's order

  /// An SVG transform list: the last step applies to the point first.
  static func svg(_ steps: CGAffineTransform...) -> CGAffineTransform {
    steps.reversed().reduce(.identity) { $0.concatenating($1) }
  }

  static func translate(_ x: CGFloat, _ y: CGFloat) -> CGAffineTransform {
    CGAffineTransform(translationX: x, y: y)
  }

  static func scale(_ x: CGFloat, _ y: CGFloat? = nil) -> CGAffineTransform {
    CGAffineTransform(scaleX: x, y: y ?? x)
  }

  /// SVG `rotate(degrees cx cy)`.
  static func rotate(_ degrees: CGFloat, around x: CGFloat = 0, _ y: CGFloat = 0)
    -> CGAffineTransform
  {
    about(x, y, CGAffineTransform(rotationAngle: degrees * .pi / 180))
  }

  /// `inner` applied about (x, y).
  static func about(_ x: CGFloat, _ y: CGFloat, _ inner: CGAffineTransform) -> CGAffineTransform {
    svg(translate(x, y), inner, translate(-x, -y))
  }

  /// Web's `mapArt`: from the legacy art's coordinates into the front art's.
  static func mapArt(
    _ oldX: CGFloat, _ oldY: CGFloat, _ newX: CGFloat, _ newY: CGFloat, _ sx: CGFloat = unit,
    _ sy: CGFloat = unit
  ) -> CGAffineTransform {
    svg(translate(newX, newY), scale(sx, sy), translate(-oldX, -oldY))
  }

  static let legacyMap = mapArt(259, 441.35, head.x, head.y)
  static let eyeMap = mapArt(
    258.977, 292.905, 108, 121.373, (128.602 - 87.3978) / (323.121 - 194.833))

  // MARK: - Overlays (Web's `eyeOverlays`, `FACE_OVERLAYS`, `EXTRA_OVERLAYS`)

  private static let ink = hex(0x252121)
  private static let paper = hex(0xF8F5F3)
  private static let tongue = hex(0xFFC6E2)
  private static let water = hex(0x84C8EF)
  private static let blue = hex(0x3363D3)

  /// Web's `STROKE`: the legacy art's 5-unit ink line.
  private static func inked(_ id: String?, _ data: String) -> OkouAvatarNode {
    shape(id, data, stroke: ink, width: 5, cap: .round, join: .round)
  }

  private static func heart() -> OkouAvatarNode {
    shape(
      nil, "M0 8C-4 4-12-1-12-7C-12-14-4-16 0-10C4-16 12-14 12-7C12-1 4 4 0 8Z",
      fill: hex(0xE77F98), stroke: ink, width: 2.5)
  }

  private static func star() -> OkouAvatarNode {
