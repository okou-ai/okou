  private static let teardrop = Path(
    okouSVG: "M0-4C-1.1-1.5-2.5.2-2.5 1.7a2.5 2.5 0 0 0 5 0C2.5.2 1.1-1.5 0-4Z")

  private static func confettiPiece(_ index: Int) -> OkouAvatarNode {
    let color = [blue, hex(0x96D82D), hex(0xE77F98), hex(0xFFA500)][index % 4]
    let piece =
      switch index % 3 {
      case 0: shape(nil, "M-1.4-2.8H1.4V2.8H-1.4Z", fill: color)
