      side == .left
      ? "M\(frontX - 6.2) 121.7Q\(frontX) 127.1 \(frontX + 5.8) 121.4"
      : "M\(frontX - 5.8) 121.4Q\(frontX) 127.1 \(frontX + 6.2) 121.7"
    return [
      group("eye-\(name)-squeeze", opacity: 0, [inked(nil, squeeze)]),
      group(
        "eye-\(name)-spiral", transform: translate(x, 293), opacity: 0,
        [
          shape(
            nil, "M0 0c-6-6-12 3-5 8s20-1 17-12S-8-21-16-7s3 28 17 27", stroke: ink, width: 4,
            cap: .round)
        ]),
      group(
        "eye-\(name)-star", transform: svg(translate(x, 293), scale(1.35)), opacity: 0, [star()]),
      shape("eye-\(name)-cry", cry, stroke: ink, width: line, cap: .round, opacity: 0),
      shape("eye-\(name)-shine", ellipse(frontX - 1.3, 119.6, 1.6, 1.6), fill: .white, opacity: 0),
    ]
  }

