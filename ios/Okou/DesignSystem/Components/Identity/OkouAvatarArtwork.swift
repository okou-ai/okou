  private static func lined(_ node: OkouAvatarNode) -> OkouAvatarNode {
    var node = node
    node.markLines()
    return node
  }

  // MARK: - Web's `buildTemplate`

  private static func makeScene() -> OkouAvatarNode {
    var scene = source()
    // Everything but the extras moves together, so a hop carries the whole figure.
    let extras = scene.children.filter { $0.id == "extras" }
    scene.children =
      [group("character-motion", scene.children.filter { $0.id != "extras" })]
      + extras
    scene.update("torso-art") { torso in torso.children[0].id = "torso-clip" }
    for side in OkouAvatarSide.allCases {
      let (x, frontX) = eyeX(side)
      scene.update("eye-\(side.rawValue)-art") { art in art.children += eyeOverlays(side) }
      for kind in ["squeeze", "spiral", "star"] {
        scene.wrap("eye-\(side.rawValue)-\(kind)", in: mapArt(x, 292.905, frontX, 121.373))
      }
    }
    scene.update("eyes-track") { track in track.markLines() }
    scene.update("face-track") { track in track.children += faceOverlays() }
    for id in ["mouth-laugh", "mouth-kiss"] {
      scene.wrap(id, in: mapArt(287, 370, 119.5, 151))
    }
    scene.wrap("glasses", in: eyeMap)
    scene.wrap("sweat-drop", in: legacyMap)
    scene.update("extras") { extras in
      extras.children = extraOverlays().map { overlay in
        overlay.id == "party-confetti" ? overlay : group(nil, transform: legacyMap, [overlay])
      }
    }
    return scene
  }
