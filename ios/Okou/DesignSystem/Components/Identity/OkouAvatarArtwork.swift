      fill: hex(0x96D82D), stroke: ink, width: 2.5, join: .round)
  }

  /// Where each eye sits in the legacy art and in the front art.
  static func eyeX(_ side: OkouAvatarSide) -> (legacy: CGFloat, front: CGFloat) {
    side == .left ? (194.833, 87.3978) : (323.121, 128.602)
  }

  private static func eyeOverlays(_ side: OkouAvatarSide) -> [OkouAvatarNode] {
